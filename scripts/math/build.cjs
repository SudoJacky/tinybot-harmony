const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { build } = require('esbuild');

const root = path.resolve(__dirname, '../..');
const output = path.join(root, 'entry/src/main/ets/workers/MathEngine.js');
const license = path.join(root, 'entry/src/main/resources/rawfile/math/LICENSE.txt');
async function main() {
  const result = await build({
    absWorkingDir: __dirname,
    entryPoints: ['engine.mjs'],
    bundle: true,
    format: 'esm',
    target: 'es2020',
    minify: true,
    legalComments: 'none',
    banner: { js: '// MathJax 3.2.2 (Apache-2.0). Generated by scripts/math/build.cjs.' },
    plugins: [{
      name: 'copy-sparse-font-keys',
      setup(builder) {
        builder.onLoad({ filter: /mathjax-full[\\/]js[\\/]output[\\/]common[\\/]FontData\.js$/ }, ({ path: filename }) => {
          const source = fs.readFileSync(filename, 'utf8');
          // On API 20 the shared Object.assign path corrupts sparse numeric keys
          // in these tables, selecting the wrong glyphs even for ASCII digits.
          const copies = /Object\.assign\((variant\.chars|link|this\.delimiters|this\.remapChars\[name\]), (chars|delims|remap)\);/g;
          assert.equal([...source.matchAll(copies)].length, 4, 'MathJax font data copy changed');
          const contents = source.replace(copies, (_match, target, table) =>
            'for (var key of Object.keys(' + table + ')) { ' + target + '[key] = ' + table + '[key]; }');
          return { contents, loader: 'js' };
        });
      },
    }],
    write: false,
  });
  const bundle = result.outputFiles[0].text;
  const notices = 'MathJax 3.2.2\nCopyright (c) 2009-2022 The MathJax Consortium\n\n' +
    fs.readFileSync(require.resolve('mathjax-full/LICENSE'), 'utf8');
  if (process.argv.includes('--check')) {
    assert.equal(fs.readFileSync(output, 'utf8'), bundle, 'MathJax bundle is out of date');
    assert.equal(fs.readFileSync(license, 'utf8'), notices, 'MathJax license is out of date');
  } else {
    fs.mkdirSync(path.dirname(output), { recursive: true });
    fs.writeFileSync(output, bundle);
    fs.writeFileSync(license, notices);
  }
}

main().catch(error => { console.error(error); process.exitCode = 1; });
