// Share the existing native brand assets with sandboxed HTML, without network requests.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const logos = {};
for (const name of ['anthropic', 'dashscope', 'deepseek', 'google', 'ollama', 'openai', 'zai']) {
  const svg = fs.readFileSync(path.join(root, `entry/src/main/resources/base/media/logo_${name}.svg`), 'utf8').trim();
  logos[name] = 'data:image/svg+xml,' + encodeURIComponent(svg);
}
const content = '// Generated by scripts/build-provider-logos.cjs from resources/base/media/logo_*.svg.\n' +
  'export const PROVIDER_LOGOS: Record<string, string> = ' + JSON.stringify(logos, null, 2) + ';\n';
const target = path.join(root, 'entry/src/main/ets/model/ProviderLogoCatalog.ets');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== content) {
    throw new Error('Provider logo catalog is stale. Run node scripts/build-provider-logos.cjs');
  }
} else fs.writeFileSync(target, content);
console.log(`Validated ${Object.keys(logos).length} bundled provider logos.`);
