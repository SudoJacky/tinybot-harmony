// Regenerate the checked-in QuickJS asset with npm ci && npm run build.
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { build } = require('esbuild');
const { strFromU8, strToU8, unzipSync, zipSync } = require('fflate');
const PptxGenJS = require('pptxgenjs');

async function slideTemplate() {
  const deck = new PptxGenJS();
  deck.layout = 'LAYOUT_WIDE';
  deck.author = 'TinyBot';
  deck.title = 'Presentation';
  deck.subject = 'Presentation';
  const slide = deck.addSlide();
  slide.addText('Title', { x: 0.7, y: 0.6, w: 11.9, h: 1.15, fontSize: 32, bold: true,
    margin: 0, valign: 'mid', color: '173752' });
  slide.addText('Bullet', { x: 0.75, y: 2, w: 11.85, h: 4.8, fontSize: 21,
    margin: 0, valign: 'top', bullet: true, color: '263C51', paraSpaceAfter: 9 });
  const entries = unzipSync(await deck.write({ outputType: 'uint8array' }), { filter: ({ name }) => !name.endsWith('/') });
  entries['docProps/core.xml'] = strToU8(strFromU8(entries['docProps/core.xml'])
    .replace(/\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ/g, '2020-01-01T00:00:00Z'));
  return Buffer.from(zipSync(entries, { level: 3, mtime: new Date(2020, 0, 1) })).toString('base64');
}

async function main() {
  const rawfile = path.resolve(__dirname, '../../entry/src/main/resources/rawfile');
  const result = await build({
    entryPoints: [path.join(__dirname, 'index.mjs')],
    bundle: true,
    write: false,
    format: 'iife',
    globalName: 'OfficeJob',
    minify: true,
    legalComments: 'inline',
    define: { __SLIDE_TEMPLATE__: JSON.stringify(await slideTemplate()) },
    banner: { js: '/* Generated by scripts/office/build.cjs. See rawfile/THIRD_PARTY_NOTICES.txt. */' },
  });
  const licenses = await Promise.all(['fflate', '@xmldom/xmldom', 'pptxgenjs'].map(async (name) => {
    const license = await fs.readFile(path.join(__dirname, 'node_modules', name, 'LICENSE'), 'utf8');
    return name + '\n\n' + license.replace(/\r\n/g, '\n').trim() + '\n';
  }));
  const outputs = [
    ['office/office.bundle.js', result.outputFiles[0].text],
    ['licenses/office-bundle.txt', licenses.join('\n---\n\n')],
  ];
  for (const [name, data] of outputs) {
    const target = path.join(rawfile, name);
    if (process.argv.includes('--check')) {
      assert.equal((await fs.readFile(target, 'utf8')).replace(/\r\n/g, '\n'), data, name + ' is stale');
    }
    else await fs.writeFile(target, data);
  }
}

main().catch((error) => { console.error(error); process.exitCode = 1; });
