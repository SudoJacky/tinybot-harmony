// Package text-only Skills into ArkTS; runtime needs no filesystem access to the bundle.
const fs = require('node:fs'), path = require('node:path');
const root = path.resolve(__dirname, '..'), folder = path.join(root, 'skills');
const catalog = JSON.parse(fs.readFileSync(path.join(folder, 'catalog.json'), 'utf8'));
const names = new Set();
const skills = catalog.map(item => {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(item.name) || item.name.length > 64 || names.has(item.name) ||
    typeof item.title !== 'string' || !item.title.trim()) throw Error('Invalid built-in Skill entry');
  names.add(item.name);
  const directory = path.join(folder, item.name);
  const read = file => {
    const content = new TextDecoder('utf-8', { fatal: true }).decode(fs.readFileSync(path.join(directory, file))).replace(/\r\n/g, '\n');
    if (content.length > 32000 || content.includes('\0')) throw Error('Invalid Skill text: ' + file);
    return content;
  };
  const document = read('SKILL.md');
  const files = fs.readdirSync(directory, { recursive: true, withFileTypes: true }).filter(entry => entry.isFile())
    .map(entry => path.relative(directory, path.join(entry.parentPath || entry.path, entry.name)).replaceAll('\\', '/'))
    .filter(file => file !== 'SKILL.md').sort().map(file => ({ path: file, content: read(file) }));
  if (files.length > 16) throw Error('Too many references: ' + item.name);
  return { name: item.name, title: item.title, document, files };
});
const content = '// Generated by scripts/build-builtin-skills.cjs. Edit skills/ instead.\n' +
  "import { SkillFile } from './Skills';\n\n" +
  'export interface BuiltinSkillDocument { name: string; title: string; document: string; files: SkillFile[]; }\n\n' +
  'export const BUILTIN_SKILL_DOCUMENTS: BuiltinSkillDocument[] = ' + JSON.stringify(skills, null, 2) + ';\n';
const target = path.join(root, 'entry/src/main/ets/model/BuiltinSkillCatalog.ets');
// The bundled wallet and its authoring reference share one HTML source.
const wallet = skills.find(skill => skill.name === 'widget').files.find(file => file.path === 'assets/balance.html').content;
const walletTarget = path.join(root, 'entry/src/main/ets/model/BalancePanelTemplate.ets');
const walletContent = '// Generated by scripts/build-builtin-skills.cjs. Edit skills/widget/assets/balance.html instead.\n' +
  'export const BALANCE_PANEL_HTML: string = ' + JSON.stringify(wallet) + ';\n';
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== content) throw Error('Built-in Skills are stale. Run node scripts/build-builtin-skills.cjs');
  if (fs.readFileSync(walletTarget, 'utf8').replace(/\r\n/g, '\n') !== walletContent) throw Error('Balance template is stale. Run node scripts/build-builtin-skills.cjs');
} else {
  fs.writeFileSync(target, content);
  fs.writeFileSync(walletTarget, walletContent);
}
console.log(`Validated ${skills.length} bundled Skills.`);
